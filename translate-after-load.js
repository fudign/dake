function translatePage() {
  // Переводим текстовые узлы
  function translateNode(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      const text = node.textContent.trim();
      if (translations[text]) {
        node.textContent = node.textContent.replace(text, translations[text]);
      }
    } else {
      node.childNodes.forEach(translateNode);
    }
  }

  // Запускаем после полной загрузки React
  setTimeout(() => {
    translateNode(document.body);
    
    // Меняем язык страницы
    document.documentElement.lang = 'ru';
    
    // Меняем title и meta
    document.title = document.title.replace('Үйлөнүү тоюна чакыруу', 'Приглашение на свадьбу');
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) {
      metaDesc.content = metaDesc.content.replace('Үйлөнүү тоюна чакыруу', 'Приглашение на свадьбу');
    }
    
    console.log('✅ Перевод применен!');
  }, 1000);
}

// Запускаем после загрузки DOM
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', translatePage);
} else {
  translatePage();
}
